"""All analysis runs inside Exasol. Cost units = runtime seconds + scanned MB / 100 (a model, not an invoice)."""
COST = "(RUNTIME_MS / 1000.0 + SCANNED_MB / 100.0)"
PATTERN = "REGEXP_REPLACE(REGEXP_REPLACE(SQL_TEXT, '''[^'']*''', '?'), '[0-9]+', '?')"

MONTHLY = f"""SELECT TO_CHAR(TS, 'YYYY-MM') AS PERIOD, COUNT(DISTINCT USER_ID) AS USERS, COUNT(*) AS QUERIES,
  SUM({COST}) AS UNITS FROM COSTLENS.QUERY_LOG GROUP BY TO_CHAR(TS, 'YYYY-MM') ORDER BY 1"""

REPEATS = f"""SELECT {PATTERN} AS PATTERN, COUNT(*) AS RUNS, COUNT(DISTINCT USER_ID) AS USERS, SUM({COST}) AS UNITS
  FROM COSTLENS.QUERY_LOG GROUP BY {PATTERN} HAVING COUNT(*) >= 100 ORDER BY UNITS DESC LIMIT 6"""

STARS = f"""SELECT COUNT(*) AS RUNS, SUM({COST}) AS UNITS FROM COSTLENS.QUERY_LOG WHERE UPPER(SQL_TEXT) LIKE 'SELECT *%'"""

BEFORE = "SELECT REGION, SUM(AMOUNT) FROM COSTLENS.SALES WHERE SALE_DATE >= DATE '2026-06-01' GROUP BY REGION"
FIX = """CREATE OR REPLACE TABLE COSTLENS.SALES_DAILY AS
  SELECT SALE_DATE, REGION, SUM(AMOUNT) AS AMOUNT FROM COSTLENS.SALES GROUP BY SALE_DATE, REGION"""
AFTER = "SELECT REGION, SUM(AMOUNT) FROM COSTLENS.SALES_DAILY WHERE SALE_DATE >= DATE '2026-06-01' GROUP BY REGION"

def decompose(m):
    """cost = users x queries/user x cost/query, first vs last month."""
    a, b = m.iloc[0], m.iloc[-1]
    u = b.USERS / a.USERS
    q = (b.QUERIES / b.USERS) / (a.QUERIES / a.USERS)
    c = (b.UNITS / b.QUERIES) / (a.UNITS / a.QUERIES)
    return u, q, c, u * q * c

TEAMS = f"SELECT TEAM, COUNT(*) AS RUNS, SUM({COST}) AS UNITS FROM COSTLENS.QUERY_LOG GROUP BY TEAM ORDER BY UNITS DESC"
DASHBOARDS = f"SELECT DASHBOARD, COUNT(*) AS RUNS, SUM({COST}) AS UNITS FROM COSTLENS.QUERY_LOG GROUP BY DASHBOARD ORDER BY UNITS DESC"
# Heavy = over 5 s. Peak = 10:00-15:59.
PEAK = f"""SELECT COUNT(*) AS RUNS, SUM({COST}) AS UNITS,
  SUM(CASE WHEN EXTRACT(HOUR FROM TS) BETWEEN 10 AND 15 THEN {COST} ELSE 0 END) AS PEAK_UNITS
  FROM COSTLENS.QUERY_LOG WHERE RUNTIME_MS > 5000"""
# Tables whose name never appears in any logged query.
UNUSED = """SELECT c.TABLE_NAME, c.SIZE_MB FROM COSTLENS.TABLE_CATALOG c
  WHERE NOT EXISTS (SELECT 1 FROM COSTLENS.QUERY_LOG q WHERE LOWER(q.SQL_TEXT) LIKE '%' || LOWER(c.TABLE_NAME) || '%')
  ORDER BY c.SIZE_MB DESC"""

HOURLY = f"SELECT EXTRACT(HOUR FROM TS) AS HR, SUM({COST}) AS UNITS FROM COSTLENS.QUERY_LOG GROUP BY EXTRACT(HOUR FROM TS) ORDER BY 1"

DAILY = f"SELECT TO_CHAR(TS, 'YYYY-MM-DD') AS D, SUM({COST}) AS UNITS FROM COSTLENS.QUERY_LOG GROUP BY TO_CHAR(TS, 'YYYY-MM-DD') ORDER BY 1"
DAYTOP = f"""SELECT D, PATTERN, UNITS FROM (SELECT TO_CHAR(TS, 'YYYY-MM-DD') AS D, {PATTERN} AS PATTERN, SUM({COST}) AS UNITS,
  ROW_NUMBER() OVER (PARTITION BY TO_CHAR(TS, 'YYYY-MM-DD') ORDER BY SUM({COST}) DESC) AS RN
  FROM COSTLENS.QUERY_LOG GROUP BY TO_CHAR(TS, 'YYYY-MM-DD'), {PATTERN}) t WHERE RN = 1"""

# Forecast inputs. Runaway queries (>= 60 s) are one-off incidents, so the trend baseline excludes them.
BASE = "RUNTIME_MS < 60000"
TEAMMONTH = f"SELECT TEAM, TO_CHAR(TS, 'YYYY-MM') AS PERIOD, SUM({COST}) AS UNITS FROM COSTLENS.QUERY_LOG WHERE {BASE} GROUP BY TEAM, TO_CHAR(TS, 'YYYY-MM') ORDER BY 1, 2"
INCIDENTS = f"SELECT COUNT(*) AS RUNS, COALESCE(SUM({COST}), 0) AS UNITS FROM COSTLENS.QUERY_LOG WHERE RUNTIME_MS >= 60000"
def userrisk(last, prev):
    return f"""SELECT USER_ID, TEAM, SUM(CASE WHEN TO_CHAR(TS,'YYYY-MM') = '{last}' THEN {COST} ELSE 0 END) AS LAST_U,
      SUM(CASE WHEN TO_CHAR(TS,'YYYY-MM') = '{prev}' THEN {COST} ELSE 0 END) AS PREV_U
      FROM COSTLENS.QUERY_LOG WHERE {BASE} GROUP BY USER_ID, TEAM ORDER BY LAST_U - PREV_U DESC LIMIT 5"""
